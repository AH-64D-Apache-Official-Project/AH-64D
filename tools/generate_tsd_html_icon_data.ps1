# Converts the TSD's point textures (tsdIcons, fcrIcons, aseIcons, cursor) to the HTML TSD's committed ui/tsd/tsd_icon_data.js,
# keyed by file name without _ca, lower case (fza_mpd_fnc_tsdHtmlDraw) — run when icon art changes

$ErrorActionPreference = "Stop"

$texDir  = "$PSScriptRoot\..\addons\fza_ah64_mpd\tex"
$outFile = "$PSScriptRoot\..\addons\fza_ah64_mpd\ui\tsd\tsd_icon_data.js"

$hemtt = Get-Command hemtt -ErrorAction SilentlyContinue
if ($null -eq $hemtt) {
    Write-Error "hemtt not found on PATH. Install from https://hemtt.dev/"
    exit 1
}

$paaFiles = @(foreach ($sub in "tsdIcons", "fcrIcons", "aseIcons", "cursor") {
    Get-ChildItem -Path (Join-Path $texDir $sub) -Recurse -Filter "*.paa"
}) | Sort-Object Name
if ($paaFiles.Count -eq 0) {
    Write-Error "No .paa files found in $texDir"
    exit 1
}

$tmpDir = Join-Path $env:TEMP ("tsd_html_icon_data_" + [System.Guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Path $tmpDir | Out-Null

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("// The HTML TSD's point textures as data URIs, keyed by file name without _ca, lower case - generated by")
$lines.Add("// tools/generate_tsd_html_icon_data.ps1. Do not edit manually; re-run the script when the icon textures change.")
$lines.Add("var _tsdIconData = {")

$seen = @{}
try {
    for ($i = 0; $i -lt $paaFiles.Count; $i++) {
        $paa = $paaFiles[$i]
        $key = ($paa.BaseName -replace '_ca$', '').ToLower()
        if ($seen.ContainsKey($key)) {
            Write-Error "Two textures share the key ${key}: $($seen[$key]) and $($paa.FullName)"
            exit 1
        }
        $seen[$key] = $paa.FullName
        $png = Join-Path $tmpDir ($key + ".png")

        & hemtt utils paa convert $paa.FullName $png
        if ($LASTEXITCODE -ne 0 -or -not (Test-Path $png)) {
            Write-Error "hemtt utils paa convert failed for $($paa.Name)"
            exit 1
        }

        $b64   = [System.Convert]::ToBase64String([System.IO.File]::ReadAllBytes($png))
        $comma = if ($i -lt ($paaFiles.Count - 1)) { "," } else { "" }
        $lines.Add("  '${key}': 'data:image/png;base64,${b64}'${comma}")
    }
} finally {
    Remove-Item -Path $tmpDir -Recurse -Force -ErrorAction SilentlyContinue
}

$lines.Add("};")

$content = [string]::Join("`n", $lines) + "`n"
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($outFile, $content, $utf8NoBom)

Write-Host ("Generated " + $outFile + " (" + $paaFiles.Count + " icons)") -ForegroundColor Green
